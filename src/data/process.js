// The twelve steps behind the homepage "How it gets built" tabs
// (components/ProcessTabs.js): one sequence per service, six drawings each.
//
// Both sequences are the five stages every project shares (data/work.js
// `stages`: Scope, Build, Integrate, Hand over, Stabilise) told from each
// service's side with one extra beat each — the free walkthrough for a
// Build-a-Bot, the blueprint for a property — so the homepage cannot describe
// a different project from /build-a-bot/ and /work/. Day counts and the
// oversight floor are derived from data/build-a-bot.js, never retyped.
//
// The drawings are generated by scripts/process/pipeline.sh from the prompts
// in scripts/process/prompts/ and encoded to public/assets/process/ as
// <track>-<nn>.webp (1440w) and <track>-<nn>-m.webp (720w), 3:2: graphite
// pencil on drafting paper, isometric, one element in the track's colour.
// Both sets show the PROCESS AS A TEAM WITH THE CLIENT, drawn as pencil
// presentation sketches with entourage figures (brief of 2026-09-10: "what
// happens when they build", fictional where that tells it better). A small
// cast recurs: the client in a cardigan with a notebook, studio figures in
// aprons. Build-a-Bot: the client walks the team through the shop, signs the
// one-page letter while the robot is still a dashed outline, the team builds
// and wires it, the client watches its first trial, it takes the back-office
// desk, an engineer watches the gauges through the first month. Site & app:
// the property is a stage set (three page panels under an arched header on a
// round platform with footlights, described identically in every prompt):
// a maquette on the kickoff table, wireframes pinned and strung on a wall,
// panels hoisted, a tripod gauge on the test, the ribbon on opening night,
// keys at the platform's edge. `alt` describes the drawing, not the step;
// the caption says the step.

import { cta, routes } from "./site";
import { notDelegate, oversight, terms, usd } from "./build-a-bot";

const ART_W = 1440;
const ART_H = 960;

const art = (track, n) => {
  const nn = String(n).padStart(2, "0");
  return {
    src: `/assets/process/${track}-${nn}.webp`,
    srcSet: `/assets/process/${track}-${nn}-m.webp 720w, /assets/process/${track}-${nn}.webp ${ART_W}w`,
    width: ART_W,
    height: ART_H,
  };
};

/** Attach the artwork slot to each step so the component never builds a path. */
const withArt = (track, steps) =>
  steps.map((step, i) => ({ ...step, art: art(track, i + 1) }));

